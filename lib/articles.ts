export function getArticle(slug: string): Article | undefined {
  return articles.find((article) => article.slug === slug);
}

export const articleSlugs: string[] = articles.map((article) => article.slug);

/** Blocks that feed FAQPage schema — derived, so the schema cannot drift from the copy. */
export function articleFaqs(article: Article): { q: string; a: string }[] {
  const answer = article.blocks.find((b) => b.kind === "answer");
  const faq = article.blocks.find((b) => b.kind === "faq");
  return [
    ...(answer && answer.kind === "answer" ? [{ q: answer.q, a: answer.a }] : []),
    ...(faq && faq.kind === "faq" ? faq.items : []),
  ];
}
