export function getLocation(slug: string): Location | undefined {
  return locations.find((location) => location.slug === slug);
}

export const locationSlugs: string[] = locations.map(
  (location) => location.slug,
);

// `nearby` is BIDIRECTIONAL, and the route drops a slug it cannot resolve without a word — so a typo or a
// one-way edge would vanish from the page silently. Module scope, so every build fails on it (the footer
// imports this file on every route), not only the city pages that happen to be generated.
for (const location of locations) {
  for (const slug of location.nearby) {
    const other = getLocation(slug);
    if (!other) {
      throw new Error(
        `lib/locations.ts: '${location.slug}' lists nearby '${slug}', which is not a location.`,
      );
    }
    if (!other.nearby.includes(location.slug)) {
      throw new Error(
        `lib/locations.ts: the nearby edge '${location.slug}' → '${slug}' is one-way — add it to both.`,
      );
    }
  }
}
