export interface LocationClaim {
  /** One specific, true, city-relevant statement. Rendered as local substance. */
  text: string;
  /** Kept so an auditor can see WHY this claim was considered city-specific. */
  category: "housing-stock" | "neighbourhood" | "travel" | "infrastructure";
}

export interface Location {
  /** ASCII kebab-case, matching the /services/ convention. */
  slug: string;
  /**
   * ISO date of the last MEANINGFUL change to what this page shows — for a new city, the day it
   * first deploys. app/sitemap.ts emits it as <lastmod>; bump it in the same commit as the change.
   * A metaDescription or OG edit does not count.
   */
  lastModified: string;
  /** Display name, e.g. תל אביב */
  name: string;
  /** Drives City vs AdministrativeArea in the schema. */
  kind: "city" | "region";
  /**
   * The name WITH its preposition — בתל אביב, באזור השרון, בצפון הארץ.
   * Exists because a bare `ב${name}` is wrong Hebrew for regions and reads badly for
   * hyphenated names (בתל אביב-יפו). No template should ever guess this.
   */
  prefixed: string;
  /**
   * The AEO answer block: a question-form heading and a 40–60 word answer, complete in its first
   * sentence. The same `{ q, a }` shape as a service's `answer` and an article's `answer` block —
   * which is the point. A string could not reach `faqPageJsonLd`, and locations were the ONLY page
   * type whose answer block never joined the FAQ graph even though it is genuine on-page Q&A
   * (finding AEO-5). `q` is the text rendered as the visible H2, so the two can never diverge.
   * The first three cities (tel-aviv, holon, bat-yam) kept the exact H2 they had already been
   * rendering, so for them the change was structural only; the nine added 2026-10-28 use the same
   * question form. A new city may write a better real question.
   */
  answer: { q: string; a: string };
  /**
   * The SERP snippet, 150–160 chars, written to the Location formula in docs/keyword-map.md §3
   * and ending in a call to action with the phone number.
   *
   * This field exists because the route used to do `answer.slice(0, 155)`, which cut all three
   * cities mid-word — בת ים's page severed its own name (finding SEO-02). It must be authored, not
   * derived: the answer block already appears in the first visible paragraph, so reusing it wastes
   * the one field that can carry a distinct hook.
   */
  metaDescription: string;
  /** 2–3 paragraphs of genuinely city-specific intro. */
  intro: string[];
  /** The local substance — three or more, or the city does not ship. */
  claims: LocationClaim[];
  /** Realistic scheduling at this distance. Never promise same-day where it is not true. */
  travel: string;
  /** City-specific FAQ — should read ODDLY on any other city's page. */
  faqs: { q: string; a: string }[];
  /** Adjacent location slugs. The edge is BIDIRECTIONAL — add this city to theirs too. */
  nearby: string[];
}

